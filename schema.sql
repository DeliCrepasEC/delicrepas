-- DeliCrepas: schema para Supabase (PostgreSQL)
create extension if not exists pgcrypto;

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  category text not null default 'Otros',
  price numeric(10,2) not null check (price >= 0),
  emoji text default '🍽️',
  available boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.store_settings (
  id integer primary key check (id = 1),
  delivery_fee numeric(10,2) not null default 1.00 check (delivery_fee >= 0),
  packaging_fee numeric(10,2) not null default 0.25 check (packaging_fee >= 0),
  business_name text not null default 'DeliCrepas',
  whatsapp text default ''
);
insert into public.store_settings(id) values(1) on conflict(id) do nothing;

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  customer_phone text not null default '',
  delivery_address text not null default '',
  order_type text not null default 'delivery' check(order_type in ('delivery','local')),
  payment_method text not null default 'Efectivo al recibir',
  status text not null default 'new' check(status in ('new','preparing','ready','completed','cancelled')),
  subtotal numeric(10,2) not null default 0,
  delivery_fee numeric(10,2) not null default 0,
  packaging_fee numeric(10,2) not null default 0,
  total numeric(10,2) not null default 0,
  notes text default '',
  items jsonb not null default '[]'::jsonb,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);
create index if not exists orders_created_at_idx on public.orders(created_at desc);

-- Calcula precios desde la base de datos; no confía en totales enviados por el navegador.
create or replace function public.calculate_order_totals()
returns trigger language plpgsql security definer set search_path = public as $$
declare item jsonb; pid uuid; qty integer; price numeric(10,2); line_total numeric(10,2); sub numeric(10,2) := 0; fee_delivery numeric(10,2) := 0; fee_pack numeric(10,2) := 0; clean_items jsonb := '[]'::jsonb; p record;
begin
  if jsonb_typeof(new.items) <> 'array' or jsonb_array_length(new.items) = 0 then
    raise exception 'El pedido debe incluir productos';
  end if;
  for item in select value from jsonb_array_elements(new.items) loop
    pid := (item->>'product_id')::uuid;
    qty := greatest(1, least(100, coalesce((item->>'quantity')::integer,1)));
    select id,name,price,available into p from public.products where id=pid;
    if not found or (new.order_type='delivery' and not p.available) then raise exception 'Producto no disponible'; end if;
    price := p.price; line_total := price * qty; sub := sub + line_total;
    clean_items := clean_items || jsonb_build_array(jsonb_build_object('product_id',p.id,'name',p.name,'quantity',qty,'unit_price',price,'line_total',line_total));
  end loop;
  if new.order_type='delivery' then
    select delivery_fee,packaging_fee into fee_delivery,fee_pack from public.store_settings where id=1;
  end if;
  new.items := clean_items; new.subtotal := sub; new.delivery_fee := coalesce(fee_delivery,0); new.packaging_fee := coalesce(fee_pack,0); new.total := sub + coalesce(fee_delivery,0) + coalesce(fee_pack,0);
  if new.order_type='delivery' then new.status := 'new'; end if;
  return new;
end $$;
drop trigger if exists orders_calculate_totals on public.orders;
create trigger orders_calculate_totals before insert on public.orders for each row execute function public.calculate_order_totals();

alter table public.products enable row level security;
alter table public.store_settings enable row level security;
alter table public.orders enable row level security;

-- Menú público solo muestra productos disponibles.
drop policy if exists "public reads available products" on public.products;
create policy "public reads available products" on public.products for select to anon, authenticated using (available or auth.uid() is not null);
drop policy if exists "admins manage products" on public.products;
create policy "admins manage products" on public.products for all to authenticated using (true) with check (true);

drop policy if exists "public reads delivery settings" on public.store_settings;
create policy "public reads delivery settings" on public.store_settings for select to anon, authenticated using (id=1);
drop policy if exists "admins manage settings" on public.store_settings;
create policy "admins manage settings" on public.store_settings for all to authenticated using (true) with check (true);

drop policy if exists "customers submit delivery orders" on public.orders;
create policy "customers submit delivery orders" on public.orders for insert to anon, authenticated with check (order_type='delivery' and status='new' and created_by is null);
drop policy if exists "admins read orders" on public.orders;
create policy "admins read orders" on public.orders for select to authenticated using (true);
drop policy if exists "admins update orders" on public.orders;
create policy "admins update orders" on public.orders for update to authenticated using (true) with check (true);
drop policy if exists "admins submit local sales" on public.orders;
create policy "admins submit local sales" on public.orders for insert to authenticated with check (order_type='local' and created_by=auth.uid());

